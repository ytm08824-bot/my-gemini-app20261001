import { Dungeon, DungeonFloor, Enemy, Gimmick } from '../types/game';

// Helper to generate consistent floors for large multi-floor dungeons
function generateDungeonFloors(config: {
  dungeonId: string;
  totalFloors: number;
  basePoints: number;
  level: number;
  statPrimary: 'dexterity' | 'mobility' | 'endurance' | 'observation' | 'knowledge' | 'social';
  statPrimaryName: string;
  statSecondary: 'dexterity' | 'mobility' | 'endurance' | 'observation' | 'knowledge' | 'social';
  statSecondaryName: string;
  enemyPool: Enemy[];
  harvestPool: { itemId: string; weight: number }[];
  floorBosses?: Record<number, Enemy>;
  finalBoss: Enemy;
}): DungeonFloor[] {
  const floors: DungeonFloor[] = [];

  for (let f = 1; f <= config.totalFloors; f++) {
    const isFinal = f === config.totalFloors;
    const floorBoss = config.floorBosses ? config.floorBosses[f] : undefined;
    const boss = isFinal ? config.finalBoss : floorBoss;

    const statKey = f % 2 === 1 ? config.statPrimary : config.statSecondary;
    const statName = f % 2 === 1 ? config.statPrimaryName : config.statSecondaryName;
    const difficulty = Math.min(28, Math.round(8 + (config.level * 0.45) + (f * 0.3)));

    const floorEnemies = isFinal
      ? []
      : config.enemyPool.map((e, idx) => ({
          ...e,
          id: `${config.dungeonId}_f${f}_e${idx}`,
          hp: Math.round(e.hp * (1 + (f - 1) * 0.04)),
          maxHp: Math.round(e.maxHp * (1 + (f - 1) * 0.04)),
          atk: Math.round(e.atk * (1 + (f - 1) * 0.035)),
          def: Math.round(e.def * (1 + (f - 1) * 0.035)),
          expReward: Math.round(e.expReward * (1 + (f - 1) * 0.05)),
          goldReward: Math.round(e.goldReward * (1 + (f - 1) * 0.05)),
        }));

    const isSocial = statKey === 'social';
    const gimmickTitle = isSocial
      ? `${f}層の迷宮交渉・対話試練`
      : `${f}層の関門仕掛け`;
    const gimmickDesc = isSocial
      ? `迷宮を彷徨う精霊や守護者の意思が語りかけてくる。友好的に対話し、道を切り開け！(${statName}判定)`
      : `深部へ進むための道が阻まれている。突破の道を見出せ！(${statName}判定)`;

    const floorGimmicks: Gimmick[] = isFinal
      ? []
      : [
          {
            id: `${config.dungeonId}_gimmick_f${f}`,
            title: gimmickTitle,
            description: gimmickDesc,
            requiredStat: statKey,
            statName: statName,
            difficulty: difficulty,
            successExp: Math.round(20 + config.level * 5 + f * 4),
            successReward: { itemId: config.harvestPool[0]?.itemId || 'crystal_shard', count: 1 + Math.floor(f / 8) },
            successGold: Math.round(30 + config.level * 8 + f * 6),
            partialDamage: Math.round(5 + f * 1.5),
            failureDamage: Math.round(10 + f * 2.5),
            criticalSuccessBonus: isSocial
              ? '心の機微を捉えた完璧な対話！相手は感銘を受け、先へ通してくれた！'
              : '見事な判断で突破！探索ポイントを大幅に進めた！',
          },
        ];

    floors.push({
      floorNumber: f,
      name: isFinal ? `最深第${f}層：深奥の間` : `第${f}層：回廊`,
      maxExplorationPoints: config.basePoints,
      enemies: floorEnemies,
      gimmicks: floorGimmicks,
      harvestPool: config.harvestPool,
      boss: boss,
    });
  }

  return floors;
}

